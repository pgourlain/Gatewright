# Generates THIRD-PARTY-NOTICES.md from resolved NuGet dependencies (requires the nuget-license tool).
set -euo pipefail

cd "$(dirname "$0")/.."
tmp="$(mktemp)"
nuget-license -i Gatewright.slnx -t -a build/allowed-licenses.json -ignore build/ignored-packages.json -override build/license-overrides.json -o JsonPretty > "$tmp"

python3 - "$tmp" > THIRD-PARTY-NOTICES.md <<'PY'
import json, sys
rows = sorted(json.load(open(sys.argv[1])), key=lambda r: (r["PackageId"].lower(), r["PackageVersion"]))
print("# Third-party notices\n")
print("This file is generated by CI from the resolved dependencies. Do not edit it by hand.\n")
print("| Package | Version | License | URL | Copyright |")
print("|---|---|---|---|---|")
for r in rows:
    print("| {} | {} | {} | {} | {} |".format(
        r["PackageId"], r["PackageVersion"], r.get("License", ""),
        r.get("LicenseUrl", "") or r.get("PackageProjectUrl", ""),
        (r.get("Copyright") or "").replace("|", "/").replace("\n", " ")))
PY
rm -f "$tmp"
